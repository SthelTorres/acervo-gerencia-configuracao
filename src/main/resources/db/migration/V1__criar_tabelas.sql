-- V1: estrutura inicial do banco do Acervo (compatível com H2 e PostgreSQL)
CREATE TABLE livro (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn                   VARCHAR(13)  NOT NULL,
    titulo                 VARCHAR(200) NOT NULL,
    autor                  VARCHAR(150) NOT NULL,
    ano_publicacao         INTEGER,
    categoria              VARCHAR(60),
    exemplares_totais      INTEGER      NOT NULL,
    exemplares_disponiveis INTEGER      NOT NULL,
    CONSTRAINT uk_livro_isbn UNIQUE (isbn),
    CONSTRAINT ck_livro_exemplares CHECK (exemplares_disponiveis >= 0 AND exemplares_disponiveis <= exemplares_totais)
);

CREATE TABLE leitor (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL,
    tipo  VARCHAR(20)  NOT NULL,
    ativo BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_leitor_email UNIQUE (email)
);

CREATE TABLE emprestimo (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id                BIGINT         NOT NULL REFERENCES livro (id),
    leitor_id               BIGINT         NOT NULL REFERENCES leitor (id),
    data_emprestimo         DATE           NOT NULL,
    data_prevista_devolucao DATE           NOT NULL,
    data_devolucao          DATE,
    status                  VARCHAR(20)    NOT NULL,
    multa                   NUMERIC(10, 2) NOT NULL DEFAULT 0,
    renovacoes              INTEGER        NOT NULL DEFAULT 0
);

CREATE INDEX ix_emprestimo_leitor_status ON emprestimo (leitor_id, status);
CREATE INDEX ix_emprestimo_livro_status ON emprestimo (livro_id, status);
